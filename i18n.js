function detectLanguage() {
  const saved = localStorage.getItem("ir_lang");
  if (saved === "en" || saved === "es") return saved;
  const browser = (navigator.language || navigator.userLanguage || "en").toLowerCase();
  return browser.startsWith("es") ? "es" : "en";
}

let currentLang = detectLanguage();

function t(key) {
  return TRANSLATIONS[currentLang][key] || TRANSLATIONS["en"][key] || key;
}

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("ir_lang", lang);
  applyTranslations();
  updateLangToggle();

  // Si hay catálogo visible, recargarlo en el nuevo idioma
  if (typeof renderCatalog === "function" && typeof filteredOffers !== "undefined" && filteredOffers.length > 0) {
    renderCatalog(filteredOffers);
  }

  // Si hay planes destacados en el home, recargarlos
  if (typeof loadFeaturedPlans === "function") {
    loadFeaturedPlans();
  }

  // Disparar evento global para que otros módulos reaccionen
  window.dispatchEvent(new Event("ir_lang_changed"));
}

function applyTranslations() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const val = t(key);
    if (val !== undefined) el.innerHTML = val;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    el.placeholder = t(key);
  });
  document.documentElement.lang = currentLang;
}

function updateLangToggle() {
  document.querySelectorAll("#lang-toggle, #lang-toggle-mobile").forEach((toggle) => {
    if (toggle) {
      toggle.textContent = currentLang === "es" ? "EN" : "ES";
    }
  });
}

document.addEventListener("DOMContentLoaded", () => {
  applyTranslations();
  updateLangToggle();

  document.querySelectorAll("#lang-toggle, #lang-toggle-mobile").forEach((toggle) => {
    if (toggle) {
      toggle.addEventListener("click", () => {
        setLanguage(currentLang === "es" ? "en" : "es");
      });
    }
  });
});
