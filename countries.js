function getCountryDisplay(offer, lang) {
  const country = offer.country || "";
  if (!country) return "";

  // Si es regional
  if (country.startsWith("Regional")) {
    const labels = REGIONAL_LABELS[lang] || REGIONAL_LABELS.en;
    return labels[country] || country;
  }

  // País específico — traducir
  return translateCountry(country, lang);
}

// Términos de búsqueda adicionales por país (para encontrar por nombre en español o inglés)
function getSearchTerms(offer) {
  // Nombre del país desde campo country o desde offerId
  let country = offer.country || "";
  if (!country || country.startsWith("Regional")) {
    country = getCountryFromOfferId(offer.offerId) || "";
  }

  const region = (offer.regions || []).join(" ");
  const offerId = offer.offerId || "";
  const countryES = COUNTRY_ES[country] || "";

  return [
    country.toLowerCase(),
    countryES.toLowerCase(),
    region.toLowerCase(),
    offerId.toLowerCase(),
  ].join(" ");
}

